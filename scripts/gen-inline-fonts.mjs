// One-off: fetch the carousel's Google Fonts and emit lib/ds/fonts-inline.ts
// with base64 @font-face CSS (latin + latin-ext only) so exports don't depend
// on a cross-origin stylesheet (which breaks html-to-image) and fonts embed.
import { writeFileSync } from "node:fs";

const CSS_URL =
  "https://fonts.googleapis.com/css2?family=Sora:wght@600;700;800&family=Inter:wght@400;500;600&family=JetBrains+Mono:wght@400;500;600&family=EB+Garamond:ital,wght@1,500&display=swap";
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36";
const KEEP = new Set(["latin", "latin-ext"]);

const css = await (await fetch(CSS_URL, { headers: { "User-Agent": UA } })).text();

const blockRe = /\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g;
let out = "";
let count = 0;
for (const m of css.matchAll(blockRe)) {
  const subset = m[1];
  let block = m[2];
  if (!KEEP.has(subset)) continue;
  const urlMatch = block.match(/url\((https:\/\/[^)]+\.woff2)\)/);
  if (!urlMatch) continue;
  const buf = Buffer.from(await (await fetch(urlMatch[1], { headers: { "User-Agent": UA } })).arrayBuffer());
  const dataUri = `data:font/woff2;base64,${buf.toString("base64")}`;
  block = block.replace(urlMatch[1], dataUri);
  out += block + "\n";
  count++;
}

if (count === 0) throw new Error("no font-face blocks captured");

const ts = `// AUTO-GENERATED by scripts/gen-inline-fonts.mjs — do not edit by hand.
// Base64 @font-face for the carousel fonts (Sora, Inter, JetBrains Mono,
// EB Garamond italic; latin subsets). Inlined so image export has no
// cross-origin stylesheet dependency.
export const inlineFontFaceCss = String.raw\`
${out}\`;
`;

writeFileSync(new URL("../lib/ds/fonts-inline.ts", import.meta.url), ts);
console.log(`✅ wrote lib/ds/fonts-inline.ts (${count} font-face blocks)`);
