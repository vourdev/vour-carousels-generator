// One-off/codegen: emit lib/ds/illustrations.generated.ts with inline <svg> strings for
// a curated allowlist from unDraw, recolored to brand accent color Ember (#EE4B1A).
import { writeFileSync, readFileSync } from "node:fs";

const manifestUrl = new URL("../lib/ds/illustrations.manifest.json", import.meta.url);
const manifest = JSON.parse(readFileSync(manifestUrl, "utf-8"));

// Flatten all slugs across categories
const SLUGS = Array.from(
  new Set(Object.values(manifest).flat())
);

const BRAND_ACCENT = "#EE4B1A";
const UNDRAW_ACCENTS = [/#6c63ff/gi, /#6c5ce7/gi];

async function fetchSvgWithRetry(slug, maxRetries = 3) {
  const urls = [
    `https://cdn.undraw.co/illustrations/${slug}.svg`,
    `https://cdn.undraw.co/illustration/${slug}.svg`,
    `https://undraw.oswaldlabs.com/EE4B1A/${slug}.svg`,
  ];

  for (let attempt = 1; attempt <= maxRetries; attempt++) {
    for (const url of urls) {
      try {
        const res = await fetch(url);
        if (res.status === 200) {
          let svg = await res.text();
          if (svg.includes("<svg")) {
            // Recolor unDraw primary accent to Ember (#EE4B1A)
            for (const rx of UNDRAW_ACCENTS) {
              svg = svg.replace(rx, BRAND_ACCENT);
            }
            // Clean up XML declaration if present
            svg = svg.replace(/^<\?xml[^>]*\?>\s*/i, "").trim();
            return svg;
          }
        }
      } catch (err) {
        // Continue to next URL / attempt
      }
    }
    // Backoff delay before retry
    if (attempt < maxRetries) {
      await new Promise((r) => setTimeout(r, attempt * 500));
    }
  }
  return null;
}

const entries = [];
console.log(`Fetching ${SLUGS.length} unDraw illustrations...`);

for (const slug of SLUGS) {
  const svg = await fetchSvgWithRetry(slug);
  if (!svg) {
    console.warn(`⚠️ Warning: Failed to fetch illustration "${slug}" after retries, skipping.`);
    continue;
  }
  entries.push([slug, svg]);
}

const slugsLiteral = entries.map(([s]) => `"${s}"`).join(", ");
const svgLines = entries
  .map(([slug, svg]) => `  "${slug}": String.raw\`${svg}\`,`)
  .join("\n");

const ts = `// AUTO-GENERATED by scripts/gen-illustrations.mjs — do not edit by hand.
// Inline unDraw SVGs for the carousel illustration allowlist. Committed so rendering has
// no runtime dependency and no network (preview + PNG export both work offline).
export const ILLUSTRATION_SLUGS = [${slugsLiteral}] as const;

export const ILLUSTRATION_SVGS: Record<string, string> = {
${svgLines}
};
`;

const outUrl = new URL("../lib/ds/illustrations.generated.ts", import.meta.url);
writeFileSync(outUrl, ts);
console.log(`✅ wrote lib/ds/illustrations.generated.ts (${entries.length} illustrations)`);
