// One-off/codegen: download the curated unDraw allowlist into individual SVG files under
// lib/ds/assets/illustrations/, recolored to brand accent Ember (#EE4B1A), plus a tiny
// TS file holding just the slug union.
//
// The SVGs are deliberately NOT emitted as a TS module: importing ~1.5 MB of inline SVG
// string literals made every bundler that touched the render path drag the whole payload
// along, and it ended up in the browser bundle. As plain files they are read at request
// time by lib/ds/illustrations.server.ts (fs.readFileSync) and never reach the client.
import { writeFileSync, readFileSync, mkdirSync, rmSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const manifestUrl = new URL("../lib/ds/illustrations.manifest.json", import.meta.url);
const manifest = JSON.parse(readFileSync(manifestUrl, "utf-8"));

// Flatten all slugs across categories
const SLUGS = Array.from(
  new Set(Object.values(manifest).flat())
);

const BRAND_ACCENT = "#EE4B1A";
const UNDRAW_ACCENTS = [/#6c63ff/gi, /#6c5ce7/gi];

const assetsDir = fileURLToPath(new URL("../lib/ds/assets/illustrations/", import.meta.url));

async function fetchSvgWithRetry(slug, maxRetries = 3) {
  const urls = [
    `https://cdn.undraw.co/illustrations/${slug}.svg`,
    `https://cdn.undraw.co/illustration/${slug}.svg`,
    `https://undraw.oswaldlabs.com/EE4B1A/${slug}.svg`,
  ];

  for (let attempt = 1; attempt <= maxRetries; attempt++) {
    for (const url of urls) {
      try {
        const res = await fetch(url);
        if (res.status === 200) {
          let svg = await res.text();
          if (svg.includes("<svg")) {
            // Recolor unDraw primary accent to Ember (#EE4B1A)
            for (const rx of UNDRAW_ACCENTS) {
              svg = svg.replace(rx, BRAND_ACCENT);
            }
            // Clean up XML declaration if present
            svg = svg.replace(/^<\?xml[^>]*\?>\s*/i, "").trim();
            return svg;
          }
        }
      } catch (err) {
        // Continue to next URL / attempt
      }
    }
    // Backoff delay before retry
    if (attempt < maxRetries) {
      await new Promise((r) => setTimeout(r, attempt * 500));
    }
  }
  return null;
}

// Wipe the folder first so a slug removed from the manifest also disappears from disk —
// otherwise stale SVGs linger and renderIllustration() would still happily serve them.
rmSync(assetsDir, { recursive: true, force: true });
mkdirSync(assetsDir, { recursive: true });

const ok = [];
console.log(`Fetching ${SLUGS.length} unDraw illustrations...`);

for (const slug of SLUGS) {
  const svg = await fetchSvgWithRetry(slug);
  if (!svg) {
    console.warn(`⚠️ Warning: Failed to fetch illustration "${slug}" after retries, skipping.`);
    continue;
  }
  writeFileSync(`${assetsDir}${slug}.svg`, svg);
  ok.push(slug);
}

const slugsLiteral = ok.map((s) => `  "${s}",`).join("\n");

const ts = `// AUTO-GENERATED by scripts/gen-illustrations.mjs — do not edit by hand.
// Slug union only. The SVG bodies live as individual files in lib/ds/assets/illustrations/
// and are read server-side by lib/ds/illustrations.server.ts — keep them out of any module
// graph that a client component can reach.
export const ILLUSTRATION_SLUGS = [
${slugsLiteral}
] as const;
`;

const outUrl = new URL("../lib/ds/illustrations.slugs.generated.ts", import.meta.url);
writeFileSync(outUrl, ts);

const bytes = readdirSync(assetsDir).reduce(
  (n, f) => n + readFileSync(`${assetsDir}${f}`).length,
  0
);
console.log(
  `✅ wrote ${ok.length} SVGs to lib/ds/assets/illustrations/ (${(bytes / 1024 / 1024).toFixed(2)} MB)`
);
console.log(`✅ wrote lib/ds/illustrations.slugs.generated.ts (${ok.length} slugs)`);
